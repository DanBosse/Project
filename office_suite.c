// Limine framebuffer structures
struct limine_framebuffer {
    void *address;
    uint64_t width;
    uint64_t height;
    uint64_t pitch;
    uint16_t bpp;
    uint8_t memory_model;
    uint8_t red_mask_size;
    uint8_t red_mask_shift;
    uint8_t green_mask_size;
    uint8_t green_mask_shift;
    uint8_t blue_mask_size;
    uint8_t blue_mask_shift;
};

struct limine_framebuffer_response {
    uint64_t revision;
    uint64_t framebuffer_count;
    struct limine_framebuffer **framebuffers;
};

struct limine_framebuffer_request {
    uint64_t id[4];
    uint64_t revision;
    struct limine_framebuffer_response *response;
};

extern volatile struct limine_framebuffer_request framebuffer_request;

// Self-contained framebuffer helpers
void* get_current_framebuffer(void) {
    if (framebuffer_request.response && framebuffer_request.response->framebuffer_count > 0) {
        return framebuffer_request.response->framebuffers[0]->address;
    }
    return NULL;
}

uint32_t get_framebuffer_width(void) {
    if (framebuffer_request.response && framebuffer_request.response->framebuffer_count > 0) {
        return (uint32_t)framebuffer_request.response->framebuffers[0]->width;
    }
    return 1024;
}

uint32_t get_framebuffer_height(void) {
    if (framebuffer_request.response && framebuffer_request.response->framebuffer_count > 0) {
        return (uint32_t)framebuffer_request.response->framebuffers[0]->height;
    }
    return 768;
}

static void draw_rect(uint32_t *fb, uint32_t w, uint32_t h, int rx, int ry, int rw, int rh, uint32_t color) {
    for (int y = ry; y < ry + rh && y < (int)h; y++) {
        if (y < 0) continue;
        for (int x = rx; x < rx + rw && x < (int)w; x++) {
            if (x < 0) continue;
            fb[y * w + x] = color;
        }
    }
}

