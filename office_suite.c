static void draw_char(uint32_t *fb, uint32_t w, uint32_t h, int x, int y, char c, uint32_t color) {
    unsigned char uc = (unsigned char)c;
    if (uc > 127) return;
    const unsigned char *glyph = font8x8_basic[uc];
    for (int row = 0; row < 8; row++) {
        unsigned char line = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (line & (1 << (7 - col))) {
                int px = x + col;
                int py = y + row;
                if (px >= 0 && px < (int)w && py >= 0 && py < (int)h) {
                    fb[py * w + px] = color;
                }
            }
        }
    }
}

static void draw_string(uint32_t *fb, uint32_t w, uint32_t h, int x, int y, const char *str, uint32_t color) {
    int cx = x;
    int cy = y;
    for (int i = 0; str[i] != '\0'; i++) {
        if (str[i] == '\n') {
            cx = x;
            cy += 12;
        } else {
            draw_char(fb, w, h, cx, cy, str[i], color);
            cx += 8;
        }
    }
}

void office_suite_init(void) {
    doc_len = 82;
    comms_active = 0;
}

void office_suite_inject_telemetry(const char* data) {
    if (doc_len < 1900) {
        document_buffer[doc_len++] = '\n';
        for (int i = 0; data[i] != '\0' && doc_len < 2047; i++) {
            document_buffer[doc_len++] = data[i];
        }
        document_buffer[doc_len] = '\0';
    }
}

void office_suite_toggle_comms(void) {
    comms_active = !comms_active;
}

void office_suite_render(void) {
    uint32_t *fb = (uint32_t*)get_current_framebuffer();
    uint32_t width = get_framebuffer_width();
    uint32_t height = get_framebuffer_height();

    if (!fb) return;

    // Render Office Workspace Window
    draw_rect(fb, width, height, 60, 60, width - 120, height - 120, 0x000F172A);
    draw_rect(fb, width, height, 60, 60, width - 120, 30, 0x001E293B);
    draw_rect(fb, width, height, 80, height - 90, width - 160, 40, 0x000B0F19);

    // Render Document Text Buffer inside Workspace
    draw_string(fb, width, height, 100, 140, document_buffer, 0x00E2E8F0);
}
